export function json(data, status = 200, headers = {}) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store", ...headers },
  });
}
export const fail = (message, status = 400) => json({ error: message }, status);

export function newId() {
  const t = Date.now().toString(36);
  const r = crypto.getRandomValues(new Uint8Array(6)).reduce((s, b) => s + b.toString(16).padStart(2, "0"), "");
  return `${t}${r}`;
}

export function slugify(s) {
  return String(s || "")
    .normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "")
    .slice(0, 80) || "post";
}

// ---------- Admin check ----------
// The browser sends the Netlify Identity access token. We confirm it with the site's own
// Identity service, then check the person is an admin: either they have the "admin" role
// (set in Netlify > Identity) or their email is listed in the ADMIN_EMAILS environment variable.
// If neither is configured, nobody gets in (fail closed).
export async function requireAdmin(req) {
  const auth = req.headers.get("authorization") || "";
  if (!/^Bearer\s+\S+/.test(auth)) throw fail("Please sign in.", 401);
  const origin = new URL(req.url).origin;
  let user;
  try {
    const r = await fetch(`${origin}/.netlify/identity/user`, { headers: { authorization: auth } });
    if (!r.ok) throw new Error(String(r.status));
    user = await r.json();
  } catch {
    throw fail("Your session has expired. Please sign in again.", 401);
  }
  const email = String(user.email || "").trim().toLowerCase();
  // roles from Netlify > Identity (any capitalisation), and/or the ADMIN_EMAILS list
  const roles = ((user.app_metadata && user.app_metadata.roles) || []).map((r) => String(r).trim().toLowerCase());
  const raw = String(globalThis.Netlify?.env?.get("ADMIN_EMAILS") || process.env.ADMIN_EMAILS || "");
  // forgiving about how the list was typed: commas, semicolons, spaces, new lines or quotes
  const allow = raw.toLowerCase().replace(/["'<>]/g, " ").split(/[\s,;]+/).filter((s) => s.includes("@"));
  if (!(roles.includes("admin") || (email && allow.includes(email)))) {
    console.warn(`Admin check refused ${email}: ADMIN_EMAILS ${allow.length ? `has ${allow.length} address(es)` : "is not set for functions"}, roles [${roles.join(", ")}]`);
    throw fail(allow.length
      ? `${email} is not on this website's admin list. Ask QF Digital to add it.`
      : "Admin access isn't set up on this website yet (the ADMIN_EMAILS setting is missing). Ask QF Digital.", 403);
  }
  return { email, id: user.id, name: (user.user_metadata && user.user_metadata.full_name) || email };
}

// Wrap a handler so thrown Responses are returned and anything else is a 500.
export const handle = (fn) => async (req, context) => {
  try { return await fn(req, context); }
  catch (e) {
    if (e instanceof Response) return e;
    console.error(e);
    return fail("Something went wrong. Please try again.", 500);
  }
};

// ---------- Posts index ----------
// Each post is stored as its own JSON blob. A small "_index" blob holds the list used by
// public pages; it is rebuilt from the posts themselves after every change, so it can't drift.
export const summary = (p) => ({
  id: p.id, slug: p.slug, title: p.title, category: p.category, excerpt: p.excerpt,
  cover: p.cover || "", coverAlt: p.coverAlt || "", status: p.status,
  publishedAt: p.publishedAt || null, updatedAt: p.updatedAt, author: p.authorName || "",
  home: p.home !== false, pinned: !!p.pinned, policies: Array.isArray(p.policies) ? p.policies : [],
});
export async function rebuildIndex() {
  const s = posts();
  const { blobs } = await s.list({ prefix: "post/" });
  const all = [];
  for (const b of blobs) {
    const p = await s.get(b.key, { type: "json" });
    if (p) all.push(summary(p));
  }
  all.sort((a, b) => String(b.publishedAt || b.updatedAt).localeCompare(String(a.publishedAt || a.updatedAt)));
  await s.setJSON("_index", { items: all, builtAt: new Date().toISOString() });
  return all;
}
export async function readIndex() {
  const idx = await posts().get("_index", { type: "json" });
  return idx ? idx.items : rebuildIndex();
}

// ---------- Gallery albums ----------
// Same pattern as posts: one blob per album plus a rebuilt "_index" of summaries.
export const albumSummary = (a) => {
  const photos = Array.isArray(a.photos) ? a.photos : [];
  const cover = a.cover && photos.some((x) => x.key === a.cover) ? a.cover : (photos[0] && photos[0].key) || "";
  const coverPhoto = photos.find((x) => x.key === cover);
  return {
    id: a.id, slug: a.slug, title: a.title, date: a.date || "", place: a.place || "", status: a.status,
    cover, coverAlt: (coverPhoto && coverPhoto.alt) || a.title, count: photos.length,
    preview: photos.slice(0, 8).map((x) => ({ key: x.key, alt: x.alt || "" })),
    publishedAt: a.publishedAt || null, updatedAt: a.updatedAt,
  };
};
const albumSortKey = (a) => String(a.date || (a.publishedAt || a.updatedAt || "").slice(0, 10));
export async function rebuildAlbums() {
  const s = gallery();
  const { blobs } = await s.list({ prefix: "album/" });
  const all = [];
  for (const b of blobs) {
    const a = await s.get(b.key, { type: "json" });
    if (a) all.push(albumSummary(a));
  }
  all.sort((a, b) => albumSortKey(b).localeCompare(albumSortKey(a)) || String(b.updatedAt).localeCompare(String(a.updatedAt)));
  await s.setJSON("_index", { items: all, builtAt: new Date().toISOString() });
  return all;
}
export async function readAlbums() {
  const idx = await gallery().get("_index", { type: "json" });
  return idx ? idx.items : rebuildAlbums();
}

